"""Slack Bolt server: listens for @mentions and button clicks.

Run locally:   python -m app.slack.server

Key rule (brief, 'Asynchronous Processing'): Slack must get ack() within 3 seconds,
otherwise it retries. So every handler calls ack() FIRST, and the slow LLM/RAG work
runs in a background thread.

Buttons:
  alert card  -> [Draft PR Response]   (becomes a status line while drafting)
  draft reply -> [Approve] [Regenerate]
"""
import logging
import os
import threading
from concurrent.futures import ThreadPoolExecutor

from dotenv import load_dotenv
from slack_bolt import App
from slack_sdk import WebClient

from app import backend_client
from app.mock_backend import MOCK_ALERTS
from app.schemas import DraftResult
from app.slack import blocks

load_dotenv()
logging.basicConfig(level=os.getenv("LOG_LEVEL", "INFO"))
log = logging.getLogger("slack-server")

MODE = os.getenv("SLACK_MODE", "socket").strip()  # "socket" (local dev, no ngrok) or "http" (webhooks)

app = App(
    token=os.environ["SLACK_BOT_TOKEN"],
    signing_secret=os.getenv("SLACK_SIGNING_SECRET") if MODE == "http" else None,
    token_verification_enabled=True,
)

executor = ThreadPoolExecutor(max_workers=4)

# Prevents two drafts for the same alert if someone double-clicks
_in_flight: set[str] = set()
_in_flight_lock = threading.Lock()


def _claim(article_id: str) -> bool:
    """True if no draft is running for this article (and mark it as running)."""
    with _in_flight_lock:
        if article_id in _in_flight:
            return False
        _in_flight.add(article_id)
        return True


# ---------- @mention -------------------------------------------------------
@app.event("app_mention")
def on_mention(event, say, client):
    text = event.get("text", "").lower()
    if "demo" in text:
        for alert in MOCK_ALERTS:
            client.chat_postMessage(channel=event["channel"], **blocks.alert_message(alert))
    else:
        say(**blocks.help_message())


# ---------- [Draft PR Response] on the alert card ----------------------------
@app.action(blocks.DRAFT_ACTION_ID)
def on_draft_clicked(ack, body, client):
    ack()  # 1) answer Slack immediately (< 3 s)

    article_id = body["actions"][0]["value"]
    channel = body["channel"]["id"]
    message = body["message"]
    alert_ts = message["ts"]
    user_id = body["user"]["id"]

    if not _claim(article_id):
        client.chat_postEphemeral(channel=channel, user=user_id, text="A draft for this alert is already being generated.")
        return

    # 2) swap the Draft button for a "drafting…" status, so nobody clicks twice
    alert_attachments = message.get("attachments") or []
    _update_alert(client, channel, alert_ts, message, alert_attachments, "drafting", user_id, article_id)

    # 3) placeholder in the alert's thread
    placeholder = client.chat_postMessage(channel=channel, thread_ts=alert_ts, **blocks.loading_message())

    # 4) slow work in the background; this handler returns right away
    executor.submit(
        _generate_draft, client, channel, placeholder["ts"], article_id, user_id,
        alert_ts, message, alert_attachments,
    )


# ---------- [Regenerate] on a draft ------------------------------------------
@app.action(blocks.REGENERATE_ACTION_ID)
def on_regenerate(ack, body, client):
    ack()

    article_id = body["actions"][0]["value"]
    channel = body["channel"]["id"]
    message = body["message"]
    thread_ts = message.get("thread_ts") or message["ts"]
    user_id = body["user"]["id"]

    if not _claim(article_id):
        client.chat_postEphemeral(channel=channel, user=user_id, text="A draft for this alert is already being generated.")
        return

    # old draft stays for comparison, but loses its buttons
    client.chat_update(
        channel=channel,
        ts=message["ts"],
        text="PR response draft (superseded)",
        blocks=message.get("blocks"),
        attachments=blocks.draft_with_footer(message["attachments"], f":repeat: Regenerated by <@{user_id}> - see the newer draft below"),
    )
    placeholder = client.chat_postMessage(channel=channel, thread_ts=thread_ts, **blocks.loading_message())
    executor.submit(_generate_draft, client, channel, placeholder["ts"], article_id, user_id)


# ---------- [Approve] on a draft ----------------------------------------------
@app.action(blocks.APPROVE_ACTION_ID)
def on_approve(ack, body, client):
    ack()

    article_id = body["actions"][0]["value"]
    channel = body["channel"]["id"]
    message = body["message"]
    user_id = body["user"]["id"]

    client.chat_update(
        channel=channel,
        ts=message["ts"],
        text="PR response draft (approved)",
        blocks=message.get("blocks"),
        attachments=blocks.draft_with_footer(message["attachments"], f":white_check_mark: Approved by <@{user_id}>"),
    )
    executor.submit(_safe, backend_client.approve_draft, article_id, user_id)


# ---------- background work ----------------------------------------------------
def _generate_draft(
    client: WebClient, channel: str, placeholder_ts: str, article_id: str, user_id: str,
    alert_ts: str | None = None, alert_message: dict | None = None, alert_attachments: list | None = None,
):
    try:
        result = backend_client.draft_pr_response(article_id)
    except Exception as exc:  # never leave the user staring at the spinner
        log.exception("Draft generation failed for %s", article_id)
        result = DraftResult(status="error", reason=str(exc))
    finally:
        with _in_flight_lock:
            _in_flight.discard(article_id)

    # replace the placeholder with the final draft / refusal
    client.chat_update(channel=channel, ts=placeholder_ts, **blocks.draft_message(result, user_id, article_id))

    # and update the status line on the alert card (only for the first draft)
    if alert_ts and alert_message is not None:
        status = "ready" if result.status == "ok" else "refused"
        _update_alert(client, channel, alert_ts, alert_message, alert_attachments, status, user_id, article_id)


def _update_alert(client, channel, alert_ts, message, attachments, status, user_id, article_id):
    if not attachments:  # e.g. an old message without our card - nothing to update
        return
    try:
        client.chat_update(
            channel=channel,
            ts=alert_ts,
            text=message.get("text", "Ryanair news alert"),
            blocks=message.get("blocks"),
            attachments=blocks.alert_with_status(attachments, status, user_id, article_id),
        )
    except Exception:  # a cosmetic update must never break the draft flow
        log.exception("Could not update alert status")


def _safe(fn, *args):
    try:
        fn(*args)
    except Exception:
        log.exception("%s failed", getattr(fn, "__name__", fn))


@app.action(blocks.OPEN_ARTICLE_ACTION_ID)
def on_open_article(ack):
    ack()  # link buttons still send an event; just acknowledge it


def main():
    if MODE == "http":
        # Webhook mode: Slack calls POST /slack/events (expose locally with ngrok)
        app.start(port=int(os.getenv("PORT", "3000")))
    else:
        from slack_bolt.adapter.socket_mode import SocketModeHandler

        log.info("Starting in Socket Mode - mention the bot in Slack with 'demo'")
        SocketModeHandler(app, os.environ["SLACK_APP_TOKEN"]).start()


if __name__ == "__main__":
    main()
